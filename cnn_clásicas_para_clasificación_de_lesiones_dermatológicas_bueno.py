"""## Explicabilidad del modelo


La explicabilidad es un componente fundamental en modelos aplicados a la salud. Aunque las CNN pueden alcanzar una alta precisión, su naturaleza de “caja negra” dificulta entender qué regiones de la imagen influyen en la decisión del modelo. Para mitigar este problema, utilizaremos técnicas de Explainable AI (XAI), concretamente Grad-CAM, que permite visualizar los mapas de activación relevantes para cada predicción.

Esto es especialmente importante en dermatología, donde los profesionales necesitan saber por qué un modelo considera que una lesión es benigna o maligna, y si la red está prestando atención a características clínicas relevantes (asimetría, bordes, color, textura…)

Grad‑CAM (Gradient‑weighted Class Activation Mapping) genera un mapa de calor que muestra qué regiones de la imagen han contribuido más a la predicción del modelo.

- Colores rojos: zonas con mayor importancia.
- Colores azules: zonas con menor relevancia.

Esto nos permite verificar si el modelo está mirando la lesión o si se distrae con artefactos, sombras o bordes.
"""

import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
import cv2

def gradcam(img_array, base_model, layer_name):

    grad_model = tf.keras.models.Model(
        inputs=base_model.input,
        outputs=[base_model.get_layer(layer_name).output]
    )

    with tf.GradientTape() as tape:
        conv_outputs = grad_model(img_array, training=False)
        tape.watch(conv_outputs)
        loss = tf.reduce_mean(conv_outputs)

    grads = tape.gradient(loss, conv_outputs)
    pooled = tf.reduce_mean(grads, axis=(0, 1, 2))

    conv_outputs = conv_outputs[0]
    heatmap = tf.reduce_sum(conv_outputs * pooled, axis=-1)

    heatmap = tf.maximum(heatmap, 0)
    heatmap = heatmap / (tf.reduce_max(heatmap) + 1e-8)

    return heatmap.numpy()


def show(img_path, base_model, layer_name, title):

    img = tf.keras.utils.load_img(img_path, target_size=(224, 224))
    x = tf.keras.utils.img_to_array(img)
    x = np.expand_dims(x, axis=0)

    heatmap = gradcam(x, base_model, layer_name)
    heatmap = cv2.resize(heatmap, (224, 224))
    heatmap = np.uint8(255 * heatmap)
    heatmap = cv2.applyColorMap(heatmap, cv2.COLORMAP_JET)

    img = np.array(img)

    overlay = cv2.addWeighted(
        cv2.cvtColor(img, cv2.COLOR_RGB2BGR),
        0.6,
        heatmap,
        0.4,
        0
    )

    plt.figure(figsize=(6,6))
    plt.imshow(cv2.cvtColor(overlay, cv2.COLOR_BGR2RGB))
    plt.title(title)
    plt.axis("off")
    plt.show()


