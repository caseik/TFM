"""## Construcción de los modelos CNN

En este apartado definiremos una función que construye un modelo CNN a partir de una arquitectura base preentrenada en ImageNet. Esta función:
* congela las capas convolucionales
* añade una capa de global average pooling
* incorpora dropout para evitar sobreajuste
* finaliza con una capa densa para clasificación multiclase.

Esto nos permite reutilizar el conocimiento aprendido por los modelos en millones de imágenes.
"""

from tensorflow.keras import layers

IMG_SIZE = (224, 224)
NUM_CLASSES = 7


def build_model(base_model):

    base_model.trainable = False

    inputs = keras.Input(shape=(224,224,3))
    x = base_model(inputs, training=False)

    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dropout(0.3)(x)
    outputs = layers.Dense(NUM_CLASSES, activation="softmax")(x)

    model = keras.Model(inputs, outputs)

    model.compile(
        optimizer=keras.optimizers.Adam(1e-4),
        loss="categorical_crossentropy",
        metrics=["accuracy"]
    )

    return model


