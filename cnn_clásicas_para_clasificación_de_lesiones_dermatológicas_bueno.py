def show_misclassified(model, generator, title, n=12):

    y_true = generator.classes
    y_pred = np.argmax(model.predict(generator), axis=1)

    class_names = list(generator.class_indices.keys())

    # índices mal clasificados
    wrong_idx = np.where(y_true != y_pred)[0]

    if len(wrong_idx) == 0:
        print(f"No errors for {title}")
        return

    selected = np.random.choice(wrong_idx, min(n, len(wrong_idx)), replace=False)

    plt.figure(figsize=(15, 10))
    plt.suptitle(f"Misclassified examples - {title}", fontsize=16)

    for i, idx in enumerate(selected):

        img_path = generator.filepaths[idx]
        img = plt.imread(img_path)

        true_label = class_names[y_true[idx]]
        pred_label = class_names[y_pred[idx]]

        plt.subplot(3, 4, i+1)
        plt.imshow(img)
        plt.axis("off")
        plt.title(f"T:{true_label}\nP:{pred_label}", fontsize=9)

    plt.tight_layout()
    plt.show()


